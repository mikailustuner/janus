"""Regenerate docs/adr/README.md from the decision tables of the design documents.

    python3 scripts/adr_index.py

Each `.kiro/specs/<feature>/design.md` numbers its decisions DP1, DP2, ... (table rows or headings).
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CROSS = [
    (
        "0001-no-language-model-as-product-reader.md",
        "No language model reads documents or answers people inside the product",
    ),
    (
        "0002-pre-registered-measurements.md",
        "Every scientific measurement is pre-registered before its results exist",
    ),
    (
        "0003-backups-pulled-by-a-separate-machine.md",
        "Backups are pulled by a separate machine the server cannot reach",
    ),
    (
        "0004-synthetic-test-fixtures.md",
        "Behaviour tests use synthetic fixtures; recorded data has one contract test",
    ),
]


def main() -> None:
    rows = []
    for design in sorted((ROOT / ".kiro" / "specs").glob("*/design.md")):
        text = design.read_text(encoding="utf-8")
        ids = set(re.findall(r"^\|\s*(DP\d+)\s*\|", text, re.M))
        ids |= set(re.findall(r"^#+\s*(DP\d+)\b", text, re.M))
        title = re.search(r"^#\s+(.+)$", text, re.M)
        spec = design.parent.name
        rows.append((spec, len(ids), title.group(1).strip() if title else spec))
    total = sum(n for _, n, _ in rows)
    out = [
        "# Architecture decision records",
        "",
        "Decisions are recorded where they are made: each feature's design document under",
        "`.kiro/specs/<feature>/design.md` keeps a table of design decisions numbered `DP1`,",
        "`DP2`, … with the decision and its reason. Decisions that cut across features are",
        "recorded here as short ADRs.",
        "",
        "## Cross-cutting decisions",
        "",
        "| ADR | Decision |",
        "| --- | --- |",
        *[f"| [{f[:4]}]({f}) | {d} |" for f, d in CROSS],
        "",
        f"## Decisions by feature ({total} in {len(rows)} design documents)",
        "",
        "| Feature | Design document | Decisions |",
        "| --- | --- | --- |",
        *[f"| {s} | [{t}](../../.kiro/specs/{s}/design.md) | {n} |" for s, n, t in rows],
        "",
        "This index is generated by `scripts/adr_index.py`; run it after adding a design decision.",
        "",
    ]
    (ROOT / "docs" / "adr" / "README.md").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
