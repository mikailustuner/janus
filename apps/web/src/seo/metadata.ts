import type { Metadata } from "next";
import { getTranslations } from "next-intl/server";

import {
  type Locale,
  INDEXED,
  languageAlternates,
  localizedPath,
  SITE_URL,
} from "@/seo/routes";

/** Open Graph `locale` values (language_TERRITORY). */
export const OG_LOCALE: Record<string, string> = {
  en: "en_US",
  tr: "tr_TR",
  de: "de_DE",
  fr: "fr_FR",
  es: "es_ES",
  pt: "pt_PT",
};

export const OG_SIZE = { width: 1200, height: 630 } as const;

/** An untyped translator for keys chosen at run time (the page ids and title keys of routes.ts). */
export async function translator(locale: string) {
  const t = await getTranslations({ locale: locale as Locale });
  return t as unknown as (key: string) => string;
}

/** Per-user and state pages: not indexed, links not followed (see routes.ts). */
export const noIndex: Metadata = { robots: { index: false, follow: false } };

/** The localized social image of a locale (generated by `app/[locale]/og.png`). */
export function ogImageUrl(locale: string): string {
  return `${SITE_URL}/${locale}/og.png`;
}

/**
 * Metadata of an indexed page: title, description, canonical, hreflang, Open Graph and Twitter
 * card. `locale` comes from the route params.
 */
export async function pageMetadata(
  locale: string,
  id: string,
): Promise<Metadata> {
  const route = INDEXED.find((r) => r.id === id);
  if (!route) throw new Error(`No SEO entry for page "${id}"`);
  const t = await translator(locale);
  const name = t("Metadata.title");
  const tagline = `${name} · ${t("Home.tagline.glass")}`;
  const title = id === "home" ? tagline : t(route.title);
  const description = t(id === "home" ? "Metadata.description" : `Seo.${id}`);
  const url = localizedPath(locale, route.path);
  const images = [{ url: ogImageUrl(locale), ...OG_SIZE, alt: tagline }];
  return {
    // Titles that already name Janus ("About Janus", "Janus for researchers") skip the template.
    title: title.includes(name) ? { absolute: title } : title,
    description,
    alternates: {
      canonical: url,
      languages: languageAlternates(route.path),
    },
    openGraph: {
      type: "website",
      siteName: "Janus",
      title,
      description,
      url,
      locale: OG_LOCALE[locale],
      images,
    },
    twitter: { card: "summary_large_image", title, description, images },
  };
}
