/**
 * The medicine list as a FHIR R4 (4.0.1) Bundle of type `collection` (fhir-export design §3).
 * Pure: the clock, the id source and the English ingredient names are passed in, so the same
 * input gives the same file (P6). Built in the browser only; nothing here sends anything.
 *
 * One MedicationStatement per list item, in list order (P1, P2). Ingredient codings use only the
 * WHO ATC and RxNorm system URIs (P5, DP4); the box name appears only when the person opts in
 * (P3, DP5). The subject is a contained Patient with no data at all (DP3).
 */
import type { Item } from "@/store/list";

export const FHIR_VERSION = "4.0.1";
export const ATC_SYSTEM = "http://www.whocc.no/atc";
export const RXNORM_SYSTEM = "http://www.nlm.nih.gov/research/umls/rxnorm";
export const JANUS_TAG_SYSTEM = "https://github.com/mikailustuner/janus";
export const TEST_DATA_SYSTEM =
  "http://terminology.hl7.org/CodeSystem/v3-ActReason";
export const FHIR_MIME = "application/fhir+json";

/** The file says what it is in English: it is read by systems and their staff (DP7). */
export const DISCLAIMER =
  "Generated by Janus, a research prototype, from a medicine list the person entered. Janus provides information, not medical advice. Research prototype — not a medical device. Not checked by a clinician.";
const SUBJECT_DISPLAY =
  "The person who exported this list (no identifying data)";

const ATC = /^[A-Z][0-9]{2}([A-Z]([A-Z]([0-9]{2})?)?)?$/;
const RXCUI = /^[1-9][0-9]{0,9}$/;
const MONTH = /^\d{4}-(0[1-9]|1[0-2])$/;

export interface Coding {
  system: string;
  code: string;
  display?: string;
}
export interface CodeableConcept {
  coding?: Coding[];
  text: string;
}
type Resource = Record<string, unknown> & { resourceType: string; id: string };
export interface Bundle {
  resourceType: "Bundle";
  id: string;
  meta: { tag: Coding[]; security?: Coding[] };
  type: "collection";
  timestamp: string;
  /** Absent for an empty list: FHIR JSON has no empty arrays. */
  entry?: { fullUrl: string; resource: Resource }[];
}

export interface ExportOptions {
  includeProductNames: boolean;
  demo: boolean;
  now: Date;
  /** A UUID per call (Bundle id, then one per entry). */
  newId: () => string;
  /** The accepted English name of an ingredient key, or null (vocabulary index). */
  englishName: (key: string) => string | null;
}

export interface ExportIngredient {
  key: string | null;
  labelEn: string | null;
  published: string | null;
  atc: string[];
  rxcui: string[];
}

const unique = (xs: string[]) => [...new Set(xs)];

/**
 * The ingredients of an item with the codes Janus holds for them. Combination codes chosen for a
 * component (`component_code`) code the pair, not the ingredient, and are left out (DP4).
 */
export function itemIngredients(item: Item): ExportIngredient[] {
  const c = item.candidate;
  if (c.kind === "ingredient")
    return [
      {
        key: c.ingredient_key.qid,
        labelEn: c.ingredient_key.label_en,
        published: null,
        atc: unique(c.atc_codes.map((a) => a.code).filter((x) => ATC.test(x))),
        rxcui: unique(c.rxcuis.filter((x) => RXCUI.test(x))),
      },
    ];
  return c.ingredients.map((g) => {
    const chosen =
      g.status === "ambiguous"
        ? (item.choices.find((ch) => ch.position === g.position)?.ingredient ??
          null)
        : null;
    const ownCodes = g.atc_selection !== "component_code";
    return {
      key: g.status === "mapped" ? (g.ingredient_key?.qid ?? null) : chosen,
      labelEn:
        g.status === "mapped" ? (g.ingredient_key?.label_en ?? null) : null,
      published: g.published_name,
      // An ambiguous ingredient's codes belong to no single key: only the chosen key's name is kept.
      atc:
        g.status === "mapped" && ownCodes
          ? unique(g.atc_codes.map((a) => a.code).filter((x) => ATC.test(x)))
          : [],
      rxcui:
        g.status === "mapped"
          ? unique(g.rxcuis.filter((x) => RXCUI.test(x)))
          : [],
    };
  });
}

function codings(g: ExportIngredient): Coding[] {
  return [
    ...g.atc.map((code) => ({ system: ATC_SYSTEM, code })),
    ...g.rxcui.map((code) => ({ system: RXNORM_SYSTEM, code })),
  ];
}

function concept(text: string, coding: Coding[]): CodeableConcept {
  return coding.length ? { coding, text } : { text };
}

/** FHIR strings must not be empty or only white space. */
const clean = (s: string | null | undefined) => {
  const t = (s ?? "").replace(/\s+/g, " ").trim();
  return t || null;
};

function ingredientText(g: ExportIngredient, opts: ExportOptions): string {
  return (
    clean(g.key ? opts.englishName(g.key) : null) ??
    clean(g.labelEn) ??
    clean(g.published) ??
    g.key ??
    "Unknown ingredient"
  );
}

/** Counts for the preview line: medicines, ingredients, ingredients with at least one code. */
export function exportSummary(items: readonly Item[]) {
  const ings = items.flatMap(itemIngredients);
  return {
    medicines: items.length,
    ingredients: ings.length,
    coded: ings.filter((g) => g.atc.length + g.rxcui.length > 0).length,
  };
}

function statement(item: Item, id: string, opts: ExportOptions): Resource {
  const ings = itemIngredients(item);
  const texts = ings.map((g) => ingredientText(g, opts));
  const box = opts.includeProductNames ? clean(item.boxName) : null;
  const contained: Resource[] = [{ resourceType: "Patient", id: "patient" }];
  let medication: Record<string, unknown>;
  if (ings.length === 0) {
    // No ingredient published: FHIR arrays must not be empty, so text only.
    medication = {
      medicationCodeableConcept: {
        text: box ?? "Medicine, ingredients not known",
      },
    };
  } else if (ings.length === 1) {
    // One ingredient: the codes are the medicine's; the text is what the person saw (DP4).
    medication = {
      medicationCodeableConcept: concept(box ?? texts[0]!, codings(ings[0]!)),
    };
  } else {
    // A combination: codings of different ingredients must not share one CodeableConcept.
    contained.push({
      resourceType: "Medication",
      id: "medication",
      code: { text: box ?? texts.join(" / ") },
      ingredient: ings.map((g, i) => ({
        itemCodeableConcept: concept(texts[i]!, codings(g)),
      })),
    });
    medication = { medicationReference: { reference: "#medication" } };
  }
  const started =
    item.started && MONTH.test(item.started) ? item.started : null;
  return {
    resourceType: "MedicationStatement",
    id,
    meta: { tag: tags(opts) },
    contained,
    status: "active",
    ...medication,
    subject: { reference: "#patient", display: SUBJECT_DISPLAY },
    ...(started ? { effectivePeriod: { start: started } } : {}),
    dateAsserted: opts.now.toISOString(),
    note: [{ text: DISCLAIMER }],
  };
}

function tags(opts: ExportOptions): Coding[] {
  return [
    {
      system: JANUS_TAG_SYSTEM,
      code: "generated-by-janus",
      display: "Generated by Janus, a research prototype",
    },
    ...(opts.demo
      ? [
          {
            system: JANUS_TAG_SYSTEM,
            code: "demo-synthetic-patient",
            display: "Demo · synthetic patient",
          },
        ]
      : []),
  ];
}

export function buildBundle(
  items: readonly Item[],
  opts: ExportOptions,
): Bundle {
  const bundleId = opts.newId();
  return {
    resourceType: "Bundle",
    id: bundleId,
    meta: {
      tag: tags(opts),
      // Demo data is marked with HL7's own code for test data (DP8).
      ...(opts.demo
        ? {
            security: [
              {
                system: TEST_DATA_SYSTEM,
                code: "HTEST",
                display: "test health data",
              },
            ],
          }
        : {}),
    },
    type: "collection",
    timestamp: opts.now.toISOString(),
    ...(items.length
      ? {
          entry: items.map((item) => {
            const id = opts.newId();
            return {
              fullUrl: `urn:uuid:${id}`,
              resource: statement(item, id, opts),
            };
          }),
        }
      : {}),
  };
}

/** `janus-medicines-YYYY-MM.fhir.json`, by the UTC month of `now` (DP9). */
export function fileName(now: Date): string {
  return `janus-medicines-${now.toISOString().slice(0, 7)}.fhir.json`;
}

export function serialise(bundle: Bundle): string {
  return `${JSON.stringify(bundle, null, 2)}\n`;
}
