"""The data-quality report: diff against the previous run, JSON, CSV and a Markdown summary
(data-quality design §6-§7). Pure.

A finding is `new` (not in the previous run), `persisting` (in both) or `resolved` (in the
previous run only; listed with the record it had then). The version is the rule version plus a
hash of the current findings, so the same findings give the same version.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
from collections import Counter
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any, Final

from janus.quality.checks import BDPM, CIMA, TITCK, WIKIDATA, Check, Finding, Item, Klass

RULE_VERSION: Final = "data-quality-1"
DATASET: Final = "janus-data-quality"
LICENSE: Final = "CC BY 4.0"
LICENSE_URL: Final = "https://creativecommons.org/licenses/by/4.0/"
DISCLAIMER: Final = (
    "Janus provides information, not medical advice. Research prototype — not a medical device."
)
CLASS_MEANING: Final = (
    "Classes: confirmed_error = listed in data/atc_code_exclusions.csv (expert review has not "
    "yet been done; a pharmacist must check it); needs_pharmacist = a difference "
    "no rule explains; benign_difference = a deterministic rule explains the difference (for "
    "example both regulators publish the code and the Wikidata item is outdated); it is not a "
    "pharmacist's judgement. No class is a statement about any medicine's safety."
)


def attribution(sources: Mapping[str, Mapping[str, Any]]) -> str:
    """Attribution with the update date of every source that requires one (BDPM, CIMA)."""

    def date(sid: str) -> str:
        return str(sources.get(sid, {}).get("snapshot_date") or "unknown date")

    return (
        "Janus data-quality report (ingredient identity fields compared across TİTCK, Wikidata, "
        f"openFDA NDC, BDPM and AEMPS CIMA), CC BY 4.0. Inputs: Wikidata (CC0 1.0); AEMPS CIMA / "
        f"Nomenclátor, data of {date(CIMA)}, reuse with attribution (Ley 37/2007), not an AEMPS "
        "endorsement; base de données publique des médicaments (BDPM), Licence Ouverte, version "
        f"of {date(BDPM)}, used unaltered as input (this report is a derived comparison), no "
        "official status or endorsement by ANSM, HAS or UNCAM; openFDA NDC (CC0 1.0), not an FDA "
        f"endorsement; TİTCK licensed human medicines list of {date(TITCK)}: counts only, no row, "
        "product name or barcode. ATC codes: WHO Collaborating Centre for Drug Statistics "
        "Methodology (WHOCC); group page addresses only, no index text."
    )


DICTIONARY_URL: Final = "https://github.com/mikailustuner/janus/blob/main/docs/open-data.md"
WHOCC_GROUP: Final = "https://atcddd.fhi.no/atc_ddd_index/?code={group}&showdescription=no"
STATUSES: Final = ("new", "persisting", "resolved")
NOTICES: Final = (
    "no_titck_rows_or_product_names",
    "codes_only_no_whocc_text",
    "needs_pharmacist_before_any_upstream_report",
    "not_medical_advice",
)
REVIEW_STATUS: Final = (
    "Generated by deterministic rules. Expert review has not yet been done: a pharmacist must "
    "check every finding before it is reported upstream."
)
CIMA_SUBSTANCE: Final = "eu_es_cima:substance"
HOW_TO_FIND: Final[Mapping[str, str]] = {
    TITCK: (
        "Search the current TİTCK licensed human medicines list (titck.gov.tr) for "
        "single-ingredient products of this ingredient that carry this code; `products` is how "
        "many Janus saw. Janus does not republish TİTCK rows, names or barcodes."
    ),
    CIMA: (
        "Search CIMA (cima.aemps.es) for medicines with this active ingredient and look at their "
        "ATC code; `products` is how many single-ingredient presentations Janus saw."
    ),
    WIKIDATA: "Open the Wikidata item and look at its ATC code statements (property P267).",
    f"{TITCK}+{CIMA}": (
        "Compare the codes of single-ingredient products of this ingredient in the TİTCK list "
        "and in CIMA."
    ),
    CIMA_SUBSTANCE: (
        "Search the CIMA Nomenclátor for this active-ingredient code and the names listed with it."
    ),
    BDPM: (
        "Search the BDPM composition file (CIS_COMPO_bdpm) for this substance code and the names "
        "listed with it."
    ),
}
CSV_COLUMNS: Final = (
    "dataset_version",
    "run_date",
    "finding_id",
    "status",
    "class",
    "check",
    "source",
    "key",
    "label_en",
    "code",
    "compared_codes",
    "products",
    "reasons",
    "other_keys",
    "upstream",
    "whocc_group_urls",
    "how_to_find",
)


@dataclass(frozen=True)
class RunMeta:
    run_id: str
    run_date: str  # YYYY-MM-DD, UTC
    previous_run_id: str | None
    resolution_dataset: str
    sources: Mapping[str, Mapping[str, Any]] = field(default_factory=dict[str, Mapping[str, Any]])
    code_version: str = ""


def _groups(f: Finding) -> list[str]:
    codes = [c for c in [*f.code.split("|"), *f.compared_codes] if len(c) == 7]
    if f.check is Check.substance_code_keys:
        return []
    return [WHOCC_GROUP.format(group=g) for g in sorted({c[:5] for c in codes})]


def _how(f: Finding) -> str:
    if f.check is Check.exclusion_status and f.source == WIKIDATA:
        return HOW_TO_FIND[WIKIDATA]
    if f.check is Check.substance_code_keys:
        return HOW_TO_FIND[CIMA_SUBSTANCE] if f.source == CIMA else HOW_TO_FIND[BDPM]
    return HOW_TO_FIND.get(f.source, "")


def finding_record(f: Finding, items: Mapping[str, Item]) -> dict[str, Any]:
    """The published record of one finding (no status: that depends on the previous run)."""
    item = items.get(f.key)
    return {
        "id": f.id,
        "class": f.klass.value,
        "check": f.check.value,
        "source": f.source,
        "key": f.key,
        "label_en": item.label if item is not None else None,
        "wikidata_url": f"https://www.wikidata.org/wiki/{f.key}" if f.key[:1] == "Q" else None,
        "code": f.code,
        "compared_codes": list(f.compared_codes),
        "products": f.products,
        "reasons": [r.value for r in f.reasons],
        "other_keys": list(f.other_keys),
        "upstream": f.upstream.value if f.upstream is not None else None,
        "whocc_group_urls": _groups(f),
        "how_to_find": _how(f),
    }


def version(records: Sequence[Mapping[str, Any]]) -> str:
    blob = json.dumps(
        [records_key(r) for r in sorted(records, key=lambda r: str(r["id"]))],
        sort_keys=True,
        ensure_ascii=False,
    )
    return f"{RULE_VERSION}+{hashlib.sha256(blob.encode('utf-8')).hexdigest()[:12]}"


def records_key(r: Mapping[str, Any]) -> dict[str, Any]:
    """The content of a record that defines the version (everything but the diff fields)."""
    return {k: v for k, v in r.items() if k not in ("status", "class_changed_from")}


@dataclass(frozen=True)
class Diff:
    current: list[dict[str, Any]]  # with status new | persisting (and class_changed_from)
    resolved: list[dict[str, Any]]  # previous records, status resolved


def diff(
    records: Sequence[Mapping[str, Any]], previous: Sequence[Mapping[str, Any]] | None
) -> Diff:
    before = {str(r["id"]): r for r in (previous or ())}
    current: list[dict[str, Any]] = []
    for r in sorted(records, key=lambda r: str(r["id"])):
        old = before.get(str(r["id"]))
        out = {**records_key(r), "status": "persisting" if old is not None else "new"}
        out["class_changed_from"] = (
            old["class"] if old is not None and old["class"] != r["class"] else None
        )
        current.append(out)
    now = {str(r["id"]) for r in records}
    resolved = [
        {**records_key(r), "status": "resolved", "class_changed_from": None}
        for i, r in sorted(before.items())
        if i not in now
    ]
    return Diff(current, resolved)


def summary(d: Diff) -> dict[str, Any]:
    cur = d.current
    by_check_class: dict[str, dict[str, int]] = {}
    for c in Check:
        counts = Counter(str(r["class"]) for r in cur if r["check"] == c.value)
        by_check_class[c.value] = {k.value: counts.get(k.value, 0) for k in Klass}
    by_class = Counter(str(r["class"]) for r in cur)
    by_status = Counter(str(r["status"]) for r in cur)
    return {
        "findings": len(cur),
        "by_class": {k.value: by_class.get(k.value, 0) for k in Klass},
        "by_check": {c.value: sum(by_check_class[c.value].values()) for c in Check},
        "by_check_class": by_check_class,
        "by_status": {
            "new": by_status.get("new", 0),
            "persisting": by_status.get("persisting", 0),
            "resolved": len(d.resolved),
        },
        "confirmed_errors_still_published": sum(
            1 for r in cur if r["check"] == "exclusion_status" and r["upstream"] == "persisting"
        ),
        "confirmed_errors_resolved_upstream": sum(
            1
            for r in cur
            if r["check"] == "exclusion_status" and r["upstream"] == "resolved_upstream"
        ),
    }


def build_report(
    findings: Sequence[Finding],
    items: Mapping[str, Item],
    meta: RunMeta,
    previous: Mapping[str, Any] | None,
    metrics: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    records = [finding_record(f, items) for f in findings]
    d = diff(records, previous["findings"] if previous is not None else None)
    return {
        "dataset": DATASET,
        "version": version(records),
        "run_id": meta.run_id,
        "run_date": meta.run_date,
        "previous_run_id": meta.previous_run_id,
        "previous_version": previous["version"] if previous is not None else None,
        "license": LICENSE,
        "license_url": LICENSE_URL,
        "attribution": attribution(meta.sources),
        "disclaimer": DISCLAIMER,
        "class_meaning": CLASS_MEANING,
        "dictionary_url": DICTIONARY_URL,
        "review_status": REVIEW_STATUS,
        "notices": list(NOTICES),
        "resolution_dataset": meta.resolution_dataset,
        "code_version": meta.code_version,
        "sources": {k: dict(v) for k, v in sorted(meta.sources.items())},
        "rules": RULES,
        "metrics": dict(metrics or {}),
        "summary": summary(d),
        "findings": [*d.current, *d.resolved],
    }


RULES: Final[dict[str, str]] = {
    "group": "An ATC level-4 group is the first five characters of a code (for example R06AE).",
    "exclusion_status": (
        "Each reviewed row of data/atc_code_exclusions.csv, class confirmed_error; upstream "
        "persisting when the source still publishes the code for the key, resolved_upstream "
        "when it no longer does (the row must then be removed)."
    ),
    "item_group": (
        "A code published by a regulator (TİTCK, AEMPS CIMA) on single-ingredient products of "
        "a key that shares no level-4 group with any code of the key's item (Wikidata or a "
        "curated Janus key). Benign difference only when both regulators publish the code for "
        "the key, no other key carries it and it is not a combination code; otherwise needs "
        "pharmacist."
    ),
    "regulator_group": (
        "A key with single-ingredient products in both regulators whose codes share no level-4 "
        "group; always needs pharmacist."
    ),
    "substance_code_keys": (
        "One substance code of BDPM or CIMA whose published names map to two or more keys; "
        "always needs pharmacist."
    ),
    "classes": (
        "confirmed_error: reviewed and listed in data/atc_code_exclusions.csv. needs_pharmacist: "
        "a difference no rule explains. benign_difference: a deterministic rule explains it. "
        "No class is a statement about any medicine's safety."
    ),
}


def _cell(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        return "|".join(str(v) for v in value)  # pyright: ignore[reportUnknownVariableType, reportUnknownArgumentType]
    return str(value)


def to_csv(report: Mapping[str, Any]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(CSV_COLUMNS)
    for r in report["findings"]:
        w.writerow(
            [
                report["version"],
                report["run_date"],
                r["id"],
                r["status"],
                r["class"],
                r["check"],
                r["source"],
                r["key"],
                _cell(r["label_en"]),
                r["code"],
                _cell(r["compared_codes"]),
                r["products"],
                _cell(r["reasons"]),
                _cell(r["other_keys"]),
                _cell(r["upstream"]),
                _cell(r["whocc_group_urls"]),
                r["how_to_find"],
            ]
        )
    return buf.getvalue()


def _row(r: Mapping[str, Any]) -> str:
    label = r["label_en"] or ""
    compared = ", ".join(r["compared_codes"]) or "-"
    reasons = ", ".join(r["reasons"])
    return (
        f"| {r['status']} | {r['source']} | {r['key']} {label} | {r['code']} | {compared} | "
        f"{r['products']} | {reasons} | {r['upstream'] or '-'} |"
    )


def to_markdown(report: Mapping[str, Any]) -> str:
    s = report["summary"]
    rows = report["findings"]
    lines = [
        f"# Janus data-quality report {report['run_date']}",
        "",
        f"Version `{report['version']}`, run `{report['run_id']}`, previous run "
        f"`{report['previous_run_id'] or 'none'}`. Licence {report['license']}. "
        "Generated by `python -m janus.quality.build`; do not edit by hand.",
        "",
        "Ingredient identity fields compared across TİTCK, Wikidata, openFDA NDC, BDPM and AEMPS "
        "CIMA. Codes only: no TİTCK row, product name or barcode, and no WHOCC index text. "
        + REVIEW_STATUS,
        "",
        CLASS_MEANING,
        "",
        f"Attribution: {report['attribution']}",
        "",
        f"*{DISCLAIMER}*",
        "",
        "## Summary",
        "",
        "| Class | Findings |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in s["by_class"].items()],
        "",
        "| Check | confirmed_error | needs_pharmacist | benign_difference |",
        "|---|---|---|---|",
        *[
            f"| {c} | {v['confirmed_error']} | {v['needs_pharmacist']} | {v['benign_difference']} |"
            for c, v in s["by_check_class"].items()
        ],
        "",
        f"Against the previous run: {s['by_status']['new']} new, "
        f"{s['by_status']['persisting']} persisting, {s['by_status']['resolved']} resolved. "
        f"Confirmed errors still published upstream: {s['confirmed_errors_still_published']}; "
        f"resolved upstream: {s['confirmed_errors_resolved_upstream']}.",
        "",
        "## Sources",
        "",
        "| Source | Run | Snapshot | Licence |",
        "|---|---|---|---|",
        *[
            f"| {k} | {v.get('run_id', '')} | {v.get('snapshot_date', '')} | "
            f"{v.get('license', '')} |"
            for k, v in report["sources"].items()
        ],
        "",
    ]
    sections: tuple[tuple[str, Callable[[Mapping[str, Any]], bool]], ...] = (
        (
            "Confirmed errors (owner-reviewed)",
            lambda r: r["class"] == "confirmed_error" and r["status"] != "resolved",
        ),
        (
            "New since the previous run",
            lambda r: r["status"] == "new" and r["class"] != "confirmed_error",
        ),
        ("Resolved since the previous run", lambda r: r["status"] == "resolved"),
        (
            "Needs a pharmacist, seen before",
            lambda r: r["class"] == "needs_pharmacist" and r["status"] == "persisting",
        ),
        (
            "Benign differences, seen before",
            lambda r: r["class"] == "benign_difference" and r["status"] == "persisting",
        ),
    )
    head = "| Status | Source | Key | Code | Compared with | Products | Reasons | Upstream |"
    for title, pick in sections:
        chosen = [r for r in rows if pick(r)]
        lines += [f"## {title} ({len(chosen)})", ""]
        if chosen:
            lines += [head, "|---|---|---|---|---|---|---|---|", *[_row(r) for r in chosen], ""]
        else:
            lines += ["None.", ""]
    lines += [
        "How to find each finding at its source is in the `how_to_find` field of the JSON and "
        "CSV files. Report upstream only after a pharmacist has checked the finding "
        "(`docs/contributing-corrections.md`).",
        "",
    ]
    return "\n".join(lines)
