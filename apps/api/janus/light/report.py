"""Markdown report of the retrospective validation (Req 5.2): `docs/light-face-validation.md`. Pure.

Generated from the build file, so the published numbers are the served ones. No ingredient of a
user appears: the cases are fixed, cited historical repurposings.
"""

from __future__ import annotations

from janus.light.messages import SENTENCES
from janus.light.schemas import CaseRunOut, LightFile

REASONS = {
    "hit": "hit",
    "ranked_below_top": "ranked below the top",
    "not_a_candidate": "not a candidate",
    "no_label_mapping": "no side-effect term maps to this condition, and FAERS does not list the medicine",
    "not_evaluable": "not evaluable (no label left)",
}


def _rank(r: CaseRunOut) -> str:
    if r.rank is None:
        return "—"
    span = str(r.rank.best) if r.rank.best == r.rank.worst else f"{r.rank.best}–{r.rank.worst}"
    return f"{span} of {r.rank.population}"


def _verdict(r: CaseRunOut, top_k: int) -> str:
    text = REASONS[r.reason]
    if r.hit and not r.informative:
        text += f" (uninformative: {r.population} candidates, not more than {top_k})"
    return text


def _ratio(x: float) -> str:
    return "over 1,000" if x > 1000 else f"{x:.2f}"


def render(light: LightFile) -> str:
    v = light.validation
    i = light.inputs
    goals = {g.key: g.labels["en"] for g in light.goals}
    out: list[str] = []
    w = out.append
    w("# Light face: retrospective validation")
    w("")
    w(
        "> Generated by `python -m janus.light.build --docs docs/light-face-validation.md` from build "
        f"`{light.build_id}`. Do not edit by hand. {SENTENCES['candidate_not_treatment']}"
    )
    w(
        "> Janus provides information, not medical advice. Research prototype — not a medical device."
    )
    w("")
    w(f"**Status: {v.status}.** {SENTENCES[v.status]}")
    w("")
    w("## Data snapshot")
    w("")
    w(
        f"- OnSIDES {i.onsides_release} (data release {i.onsides_date}), run `{i.onsides_run_id}`; CC BY 4.0."
    )
    w(
        f"- FAERS counts build `{i.faers_build_id}`, snapshot {i.faers_snapshot_date}, window "
        f"{', '.join(i.faers_window)}; CC0 1.0."
    )
    w(
        f"- openFDA drug labels (indications text of the case drugs), retrieved {i.openfda_date}, run `{i.openfda_run_id}`; CC0 1.0."
    )
    w(f"- Wikidata ingredient items, run `{i.wikidata_run_id}`; CC0.")
    w(
        "- Curated files (SHA-256): "
        + ", ".join(f"`{k}` {h[:12]}" for k, h in i.curated_sha256.items())
        + "."
    )
    w("")
    w("## Method")
    w("")
    w(
        "Each case names a medicine and the condition it was later used for. The engine builds its candidate list for "
        "that condition and the report gives the medicine's rank. Signals: side effects in drug labels (OnSIDES) that "
        "the curated mapping points to the condition, and FAERS reports in which the condition is reported less often "
        "than expected. Ranking: number of signal types, number of label regions, the Wilson lower bound of the share "
        "of the medicine's labels that list the effect, the number of such labels, FAERS report count; never a ratio. "
        "Equal positions share a rank range."
    )
    w("")
    w(
        "- **Primary run** (later use excluded where possible): US labels only; the case medicine's labels are removed "
        "when their openFDA indications text names the later use, or when openFDA does not have the label."
    )
    w("- **Sensitivity run**: every label of every region, nothing removed.")
    w(
        f"- **Hit**: worst rank within the top {v.top_k}. A hit among {v.top_k} or fewer candidates is uninformative."
    )
    w(f"- FAERS: {SENTENCES['faers_includes_later_use']}")
    w(f"- {SENTENCES['validation_not_blind']}")
    w("")
    w("## Results")
    w("")
    w(
        "| Case | Later use (year) | Primary: rank | Primary: result | Sensitivity: rank | Sensitivity: result | Case labels used / removed (indication, not in openFDA) |"
    )
    w("|---|---|---|---|---|---|---|")
    for c in v.cases:
        p, s = c.primary, c.sensitivity
        w(
            f"| {c.case.ingredient_name} | {goals[c.case.goal]} ({c.case.later_year}) | {_rank(p)} | {_verdict(p, v.top_k)} "
            f"| {_rank(s)} | {_verdict(s, v.top_k)} | {p.labels_used} / {p.labels_removed_indication}, "
            f"{p.labels_removed_not_in_openfda} |"
        )
    w("")
    for name, summ in (("Primary", v.primary), ("Sensitivity", v.sensitivity)):
        w(
            f"- {name}: {summ.hits} hits ({summ.informative_hits} informative), {summ.misses} misses, "
            f"{summ.not_evaluable} not evaluable, of {len(v.cases)} cases."
        )
    w("")
    w("## FAERS numbers per case (window includes the later use)")
    w("")
    w(
        "| Case | Reports with the condition | ROR (95% interval) | Reported less often than expected |"
    )
    w("|---|---|---|---|")
    for c in v.cases:
        f = c.faers
        if f is None or f.estimates is None:
            reports = f.cells.a if f else 0
            w(f"| {c.case.ingredient_name} → {goals[c.case.goal]} | {reports} | — | no |")
            continue
        e = f.estimates
        w(
            f"| {c.case.ingredient_name} → {goals[c.case.goal]} | {f.cells.a} | {_ratio(e.ror)} "
            f"({_ratio(e.ror_ci.low)}–{_ratio(e.ror_ci.high)}) | {'yes' if c.faers_inverse else 'no'} |"
        )
    w("")
    w("## Cases and sources")
    w("")
    for c in v.cases:
        w(
            f"- **{c.case.id}**: {c.case.note} Evidence: {', '.join(f'`{e}`' for e in c.case.evidence_ids)}."
        )
    w("")
    w("## Limits")
    w("")
    w(f"- {SENTENCES['label_extraction_limits']}")
    w(f"- {SENTENCES['inverse_reporting_bias']}")
    w(f"- {SENTENCES['not_checked_against_indications']}")
    w(f"- {SENTENCES['review_pending']}")
    w(
        "- Labels are not independent: generic copies repeat the same text, so label counts are an ordering device, not a sample."
    )
    w("")
    return "\n".join(out)
