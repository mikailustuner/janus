"""Markdown report of the retrospective validation (Req 5.2): `docs/light-face-validation.md`. Pure.

Generated from the build file, so the published numbers are the served ones. No ingredient of a
user appears: the cases are fixed, cited historical repurposings. Wording follows the statistician
pass (C5 to C8): informative hits lead, chance levels are given, no p-value, every limit is stated.
"""

from __future__ import annotations

from janus.light.messages import SENTENCES
from janus.light.schemas import CaseResultOut, CaseRunOut, LightFile

REASONS = {
    "hit": "hit",
    "ranked_below_top": "ranked below the top",
    "not_a_candidate": "not a candidate",
    "no_label_mapping": "no side-effect term maps to this condition",
    "not_evaluable": "not evaluable (no label left)",
}

# The first run, before the review passes (build ca2bb569c5216716, key K0, Priapism and the two
# hair-growth terms active, 9 cases). Kept so that the post-hoc changes stay visible (DP22, DP23).
FIRST_RUN = (
    "| Case | Primary | Sensitivity |",
    "|---|---|---|",
    "| minoxidil → alopecia | 1 of 127, hit | 1 of 146, hit |",
    "| sildenafil → erectile dysfunction | 6 of 68, hit | 4 of 84, hit |",
    "| topiramate → obesity | 3 of 253, hit (21 of 253 when unreadable labels are kept) | 35 of 400 |",
    "| bimatoprost → sparse eyelashes | 3 of 3 (uninformative) | 4 of 4 (uninformative) |",
    "| liraglutide → obesity | not evaluable | 295–311 of 400 |",
    "| amantadine, sildenafil → PAH, thalidomide × 2 | no side-effect term maps | same |",
)


def _rank(r: CaseRunOut) -> str:
    if r.rank is None:
        return "—"
    span = str(r.rank.best) if r.rank.best == r.rank.worst else f"{r.rank.best}–{r.rank.worst}"
    return f"{span} of {r.rank.population}"


def _verdict(r: CaseRunOut, top_k: int) -> str:
    text = REASONS[r.reason]
    if r.hit and not r.informative:
        text += f" (uninformative: {r.population} candidates, not more than {top_k})"
    return text


def _chance(r: CaseRunOut) -> str:
    if r.rank is None or r.chance_hit is None:
        return "—"
    pct = "—" if r.percentile is None else f"{r.percentile:.2f}"
    return f"{r.chance_hit:.3f} / {pct}"


def _ratio(x: float) -> str:
    return "over 1,000" if x > 1000 else f"{x:.2f}"


def _label(c: CaseResultOut, goals: dict[str, str]) -> str:
    return f"{c.case.ingredient_name} → {goals[c.case.goal]}"


def render(light: LightFile) -> str:
    v = light.validation
    i = light.inputs
    goals = {g.key: g.labels["en"] for g in light.goals}
    informative = [c for c in v.cases if c.primary.hit and c.primary.informative]
    uninformative = [c for c in v.cases if c.primary.hit and not c.primary.informative]
    unreachable = [c for c in v.cases if c.primary.reason == "no_label_mapping"]
    out: list[str] = []
    w = out.append
    w("# Light face: retrospective validation")
    w("")
    w(
        f"> Generated by `python -m janus.light.build --docs docs/light-face-validation.md` from build `{light.build_id}`. Do not edit by hand."
    )
    w(
        f"> {SENTENCES['candidate_not_treatment']} Janus provides information, not medical advice. Research prototype — not a medical device."
    )
    w(f"> {SENTENCES['review_pending']}")
    w("")
    w(f"**Status: {v.status}.** {SENTENCES[v.status]}")
    w("")
    w(
        f"**Headline:** {len(informative)} of {len(v.cases)} cases ranked in the top {v.top_k} of their condition "
        f"in the primary run among more than {v.top_k} candidates"
        + (f" ({', '.join(_label(c, goals) for c in informative)})" if informative else "")
        + f". If each case medicine had been a random candidate of its condition, about "
        f"{v.primary.expected_hits_by_chance:.2f} such hits would be expected. {SENTENCES['validation_not_blind']} "
        "This is not evidence that the method finds new candidates."
    )
    w("")
    if uninformative:
        w(
            "Uninformative (too few candidates to mean anything): "
            + ", ".join(f"{_label(c, goals)} ({_rank(c.primary)})" for c in uninformative)
            + "."
        )
    if unreachable:
        w(
            "Not reachable by construction (no side-effect term maps to the later use; these uses came from a "
            "mechanism or from patients' observations): "
            + ", ".join(_label(c, goals) for c in unreachable)
            + "."
        )
    w("")
    w("## Data snapshot")
    w("")
    w(
        f"- OnSIDES {i.onsides_release} (data release {i.onsides_date}), run `{i.onsides_run_id}`; CC BY 4.0."
    )
    w(
        f"- FAERS counts build `{i.faers_build_id}`, snapshot {i.faers_snapshot_date}, window {', '.join(i.faers_window)}; CC0 1.0."
    )
    w(
        f"- openFDA drug labels (indications text of the case medicines), retrieved {i.openfda_date}, run `{i.openfda_run_id}`; CC0 1.0."
    )
    w(f"- Wikidata ingredient items, run `{i.wikidata_run_id}`; CC0.")
    w(
        "- Curated files (SHA-256): "
        + ", ".join(f"`{k}` {h[:12]}" for k, h in i.curated_sha256.items())
        + "."
    )
    w("")
    w("## Method")
    w("")
    w(
        "Each case names a medicine and the condition it was later used for. The engine builds its candidate list for "
        "that condition and the report gives the medicine's rank. Signals: side effects in drug labels (OnSIDES) that the "
        "curated mapping points to the condition, and FAERS reports in which the condition is reported less often than "
        "expected. Ranking (key K1): has a label signal, the Wilson lower bound of the share of the medicine's labels that "
        "list the effect, the number of label regions, the number of such labels, has an inverse FAERS signal, the FAERS "
        "report count; never a ratio. Equal positions share a rank range."
    )
    w("")
    w(
        "- **Primary run** (later use excluded where possible): US labels only. Two variants for the case medicine: (a) remove its labels whose openFDA indications text names the later use; (b) also remove its labels that openFDA does not have. The published primary result is the worse of the two, and a hit counts only if both are hits."
    )
    w(
        "- **Sensitivity run**: every label of every region, nothing removed (the list a researcher sees)."
    )
    w(
        f"- **Hit**: worst rank within the top {v.top_k}. A hit among {v.top_k} or fewer candidates is uninformative. **Chance**: the probability that a random candidate of the condition lands in the top {v.top_k} ({v.top_k} / candidates); **percentile**: worst rank / candidates. No p-value is given."
    )
    w(f"- FAERS: {SENTENCES['faers_includes_later_use']}")
    w("")
    w("## Results")
    w("")
    w(
        "| Case | Later use (year of first report or approval) | Primary: rank | Primary: result | Primary: chance / percentile | (a) indication only | (b) also unreadable | Sensitivity: rank | Sensitivity: result | Case labels used / removed (indication, not in openFDA) |"
    )
    w("|---|---|---|---|---|---|---|---|---|---|")
    for c in v.cases:
        p, s = c.primary, c.sensitivity
        w(
            f"| {c.case.ingredient_name} | {goals[c.case.goal]} ({c.case.later_year}) | {_rank(p)} | {_verdict(p, v.top_k)} "
            f"| {_chance(p)} | {_rank(c.primary_indication)} | {_rank(c.primary_strict)} | {_rank(s)} | {_verdict(s, v.top_k)} "
            f"| {c.primary_strict.labels_used} / {c.primary_strict.labels_removed_indication}, "
            f"{c.primary_strict.labels_removed_not_in_openfda} |"
        )
    w("")
    for name, summ in (("Primary", v.primary), ("Sensitivity", v.sensitivity)):
        w(
            f"- {name}: {summ.informative_hits} informative hits ({summ.hits} hits in all), {summ.misses} misses, "
            f"{summ.not_evaluable} not evaluable, of {len(v.cases)} cases; about {summ.expected_hits_by_chance:.2f} informative hits expected by chance."
        )
    w("")
    w("## FAERS numbers per case (the window includes the later use)")
    w("")
    w(
        "| Case | Reports with the condition | ROR (95% interval) | Reported less often than expected |"
    )
    w("|---|---|---|---|")
    for c in v.cases:
        f = c.faers
        if f is None or f.estimates is None:
            reports = f.cells.a if f else 0
            w(f"| {_label(c, goals)} | {reports} | — | no |")
            continue
        e = f.estimates
        w(
            f"| {_label(c, goals)} | {f.cells.a} | {_ratio(e.ror)} "
            f"({_ratio(e.ror_ci.low)}–{_ratio(e.ror_ci.high)}) | {'yes' if c.faers_inverse else 'no'} |"
        )
    w("")
    w(
        "The inverse-signal layer found none of the cases. Where a ratio exists, the condition is reported more often "
        "than expected with the case medicine: this is consistent with indication and notoriety bias, and it is not "
        "evidence of harm."
    )
    w("")
    w("## Inverse signals per condition")
    w("")
    w(
        "| Condition | Pairs tested (at least 3 reports) | Reported less often than expected | Expected by chance (2.5 %) |"
    )
    w("|---|---|---|---|")
    for g in light.goals:
        if g.inverse_tested:
            w(
                f"| {g.labels['en']} | {g.inverse_tested} | {g.inverse_found} | {g.inverse_expected_by_chance:.1f} |"
            )
    w("")
    w("## Cases and sources")
    w("")
    for c in v.cases:
        w(
            f"- **{c.case.id}**: {c.case.note} Evidence: {', '.join(f'`{e}`' for e in c.case.evidence_ids)}."
        )
    w("")
    w("## Changes after the first run (post-hoc, recorded)")
    w("")
    w(
        "The first run used ranking key K0 (signal types first, then regions), counted Priapism, Abnormal hair growth and "
        "Hair growth abnormal, used only primary variant (b) and had 9 cases. The pharmacologist pass "
        "excluded the three terms (DP22) and asked for four more cases (added before the next run); the statistician pass "
        "replaced the key with K1 and asked for the two primary variants (DP23, DP24). First-run results:"
    )
    w("")
    for line in FIRST_RUN:
        w(line)
    w("")
    w("## Limits")
    w("")
    w(
        f"- {SENTENCES['validation_not_blind']} The ranking key and three mapping rows were changed after the first run's case ranks were seen."
    )
    w(
        "- Only known successes were tested: there are no negative controls, so the check cannot estimate false positives or precision."
    )
    w(f"- n = {len(v.cases)} cases; {len(unreachable)} cannot be reached by construction.")
    w(
        "- The labels that stay in the primary run are today's texts of the original-use products; their side-effect sections may have been written after the later use was known. The primary run removes labels that name the later use; it does not rebuild the labels as they were."
    )
    w(
        "- Labels are not independent: generic copies repeat the same text, so label counts are an ordering device, not a sample."
    )
    w(
        "- Inverse signals need many reports (at least 3 reports and an upper bound below 1), so they exist only for heavily reported medicines; pairs with no report at all are not evaluated."
    )
    w(f"- {SENTENCES['label_extraction_limits']}")
    w(f"- {SENTENCES['inverse_reporting_bias']}")
    w(f"- {SENTENCES['not_checked_against_indications']}")
    w("")
    return "\n".join(out)
