"""Shared fixtures for the browser port of the compartmental model (simulation-service design §5,
property S1). Writes `apps/web/src/simulation/parity.fixture.json`: raw draws of Python's
`random.Random` (Mersenne Twister, `random()`, `gauss`, `uniform`) and `explore` outputs for every
allow-listed compound and virtual population, single and repeated doses. The web test compares
its port with this file; `tests/test_simulation_properties.py` checks the file is current.

    python -m janus.simulation.parity
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Any

from janus.paths import repo_root
from janus.simulation.allowlist import AllowList, allowlist
from janus.simulation.calibration import calibration, label_half_life
from janus.simulation.compartmental import explore, horizon, params_for

FIXTURE = Path("apps/web/src/simulation/parity.fixture.json")
EXPLORER = Path("apps/web/src/simulation/explorer.json")
SEEDS = (0, 1, 42, 20261109, 2**32 + 5)


def _draws(seed: int) -> dict[str, Any]:
    r = random.Random(seed)
    rnd = [r.random() for _ in range(8)]
    gauss = [r.gauss(0.0, 1.0) for _ in range(7)]
    uni = [r.uniform(2.0, 5.0) for _ in range(3)]
    return {"seed": seed, "random": rnd, "gauss": gauss, "uniform": uni}


def cases(allow: AllowList) -> list[dict[str, Any]]:
    lim = allow.limits
    out: list[dict[str, Any]] = []
    i = 0
    for c in allow.compartmental.values():
        for pop in c.populations.values():
            schedules: list[tuple[float, int | None, int]] = [(c.dose.default, None, 1)]
            schedules += [(c.dose.low, iv, 5) for iv in c.intervals_h[:1]]
            schedules += [(c.dose.high, iv, lim.doses_max) for iv in c.intervals_h[-1:]]
            for dose, interval, doses in schedules:
                hours = horizon(doses, interval, lim.horizon_after_last_dose_h, lim.horizon_max_h)
                p = params_for(c, pop)
                seed = 20261109 + i
                i += 1
                out.append(
                    {
                        "compound": c.id,
                        "population": pop.id,
                        "params": p.__dict__,
                        "dose_mg": dose,
                        "interval_h": interval,
                        "doses": doses,
                        "hours": hours,
                        "samples": 60,
                        "seed": seed,
                        "out": explore(p, dose, hours, 60, seed, interval, doses),
                    }
                )
    return out


def build() -> dict[str, Any]:
    return {
        "about": "Generated by python -m janus.simulation.parity; do not edit.",
        "draws": [_draws(s) for s in SEEDS],
        "cases": cases(allowlist()),
    }


def explorer(allow: AllowList) -> dict[str, Any]:
    """What the in-browser explorer ships: per compound the virtual populations (medians and
    spreads), dose bounds, scenarios and validation verdict, and the limits. No person input."""
    lim = allow.limits
    return {
        "about": "Generated by python -m janus.simulation.parity from data/simulation/"
        "compounds.json and data/time_machine/compartmental_pk.csv; do not edit.",
        "version": allow.version,
        "compounds": [
            {
                "id": c.id,
                "dose_mg": {"low": c.dose.low, "default": c.dose.default, "high": c.dose.high},
                "intervals_h": list(c.intervals_h),
                "scenarios": [
                    {"id": s.id, "dose_mg": s.dose_mg, "kind": s.kind} for s in c.scenarios
                ],
                "populations": [
                    {
                        "id": p.id,
                        "reference_keys": list(p.reference_keys),
                        "params": params_for(c, p).__dict__,
                    }
                    for p in c.populations.values()
                ],
                "validation": c.validation.__dict__,
                "validated_dose_mg": [s.dose_mg for s in c.scenarios if s.kind == "validation"],
                "reference_keys": list(c.reference_keys),
            }
            for c in allow.compartmental.values()
        ],
        "calibration": calibration(),
        "label_half_life": {
            k: label_half_life()[k] for k in ("version", "source", "accuracy", "drugs")
        },
        "limits": {
            "doses_max": lim.doses_max,
            "horizon_after_last_dose_h": lim.horizon_after_last_dose_h,
            "horizon_max_h": lim.horizon_max_h,
        },
    }


def main() -> None:
    root = repo_root()
    (root / FIXTURE).write_text(json.dumps(build(), separators=(",", ":")) + "\n")
    (root / EXPLORER).write_text(json.dumps(explorer(allowlist()), indent=2) + "\n")
    print(f"wrote {FIXTURE} and {EXPLORER}")


if __name__ == "__main__":
    main()
